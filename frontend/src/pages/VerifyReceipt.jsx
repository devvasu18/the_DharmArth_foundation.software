import React, { useState, useEffect } from 'react';
import { useSearchParams, Link } from 'react-router-dom';
import { motion } from 'framer-motion';
import { ShieldCheck, AlertTriangle, Download, Home, FileText, CheckCircle2 } from 'lucide-react';
import api, { getPublicUrl } from '../services/api';
import Navbar from '../components/layout/Navbar';
import SEO from '../components/common/SEO';
import './VerifyReceipt.css';

const VerifyReceipt = () => {
    const [searchParams] = useSearchParams();
    const receiptId = searchParams.get('id');
    const [loading, setLoading] = useState(true);
    const [error, setError] = useState(false);
    const [donation, setDonation] = useState(null);
    const [lang, setLang] = useState('en');

    useEffect(() => {
        const verifyDonation = async () => {
            if (!receiptId) {
                setLoading(false);
                setError(true);
                return;
            }

            try {
                setLoading(true);
                const { data } = await api.get(`/donate/verify/${receiptId}`);
                setDonation(data);
                setError(false);
            } catch (err) {
                console.error("Verification error:", err);
                setError(true);
            } finally {
                setLoading(false);
            }
        };

        verifyDonation();
    }, [receiptId]);

    const trans = {
        en: {
            title: "Certificate Verification | The Dharmarth Medical Foundation",
            verifiedBadge: "Verified Authentic Donation",
            notFoundTitle: "Verification Failed",
            notFoundText: "We could not find any active donation receipt matching this ID. Please check the QR code or URL link.",
            donorName: "Donor Name",
            receiptNo: "Receipt No.",
            date: "Donation Date",
            amount: "Donation Amount",
            paymentMethod: "Payment Mode",
            status: "Status",
            accreditations: "Accreditations",
            ngoTitle: "THE DHARMARTH MEDICAL FOUNDATION",
            ngoReg: "NGO Reg. No.",
            ngoPan: "PAN No.",
            ngo80g: "80G Certified",
            downloadBtn: "Download PDF Certificate",
            backHome: "Back to Home",
            successStatus: "Successful Payment",
            taxEligible: "Section 80G Benefit Eligible",
            taxExemptSub: "Eligible for deduction under Section 80G of the Income Tax Act, 1961.",
            detailsHeader: "Verification Records",
            loadingText: "Verifying Receipt Authenticity..."
        },
        hi: {
            title: "प्रमाण पत्र सत्यापन | द धर्मार्थ मेडिकल फाउंडेशन",
            verifiedBadge: "सत्यापित प्रामाणिक दान",
            notFoundTitle: "सत्यापन विफल",
            notFoundText: "हमें इस आईडी से मेल खाने वाली कोई सक्रिय दान रसीद नहीं मिली। कृपया क्यूआर कोड या यूआरएल की जांच करें।",
            donorName: "दाता का नाम",
            receiptNo: "रसीद संख्या",
            date: "दान की तिथि",
            amount: "दान राशि",
            paymentMethod: "भुगतान का प्रकार",
            status: "स्थिति",
            accreditations: "मान्यताएं",
            ngoTitle: "द धर्मार्थ मेडिकल फाउंडेशन",
            ngoReg: "एनजीओ पंजीकरण संख्या",
            ngoPan: "पैन संख्या",
            ngo80g: "80G प्रमाणित",
            downloadBtn: "पीडीएफ प्रमाण पत्र डाउनलोड करें",
            backHome: "मुख्य पृष्ठ पर जाएं",
            successStatus: "सफल भुगतान",
            taxEligible: "धारा 80G कर लाभ के लिए पात्र",
            taxExemptSub: "आयकर अधिनियम, 1961 की धारा 80G के तहत कटौती के लिए पात्र।",
            detailsHeader: "सत्यापन रिकॉर्ड",
            loadingText: "रसीद की प्रामाणिकता सत्यापित की जा रही है..."
        }
    };

    const t = trans[lang];

    const toggleLang = () => {
        setLang(prev => prev === 'en' ? 'hi' : 'en');
    };

    const formattedDate = donation ? new Date(donation.createdAt).toLocaleString(lang === 'hi' ? 'hi-IN' : 'en-IN', {
        day: 'numeric', month: 'short', year: 'numeric',
        hour: '2-digit', minute: '2-digit', hour12: true
    }) : '';

    return (
        <div className="verify-page-wrapper">
            <SEO
                title={donation ? `Verified Receipt: ${donation.receiptNumber}` : "Certificate Verification"}
                description="Verify the authenticity of donation certificates generated by The DharmArth Medical Foundation."
            />
            <Navbar />

            {/* Language Switcher */}
            <div className="verify-lang-switch">
                <button onClick={toggleLang} className="btn-lang-toggle">
                    {lang === 'en' ? 'हिन्दी में देखें' : 'View in English'}
                </button>
            </div>

            <div className="verify-container">
                {loading ? (
                    <div className="verify-loader">
                        <div className="spinner"></div>
                        <p>{t.loadingText}</p>
                    </div>
                ) : error ? (
                    <motion.div
                        className="verify-card error-card"
                        initial={{ opacity: 0, scale: 0.95 }}
                        animate={{ opacity: 1, scale: 1 }}
                        transition={{ duration: 0.4 }}
                    >
                        <div className="error-icon-wrapper">
                            <AlertTriangle size={48} />
                        </div>
                        <h2>{t.notFoundTitle}</h2>
                        <p className="error-desc">{t.notFoundText}</p>
                        <div className="verify-actions">
                            <Link to="/" className="btn-home">
                                <Home size={18} />
                                {t.backHome}
                            </Link>
                        </div>
                    </motion.div>
                ) : (
                    <motion.div
                        className="verify-card success-card"
                        initial={{ opacity: 0, y: 15 }}
                        animate={{ opacity: 1, y: 0 }}
                        transition={{ duration: 0.5 }}
                    >
                        {/* Seal Header */}
                        <div className="verify-badge-header">
                            <div className="badge-icon">
                                <ShieldCheck size={28} />
                            </div>
                            <span className="badge-label">{t.verifiedBadge}</span>
                        </div>

                        {/* Title and Foundation Details */}
                        <div className="ngo-header-section">
                            <h3>{t.ngoTitle}</h3>
                            <div className="ngo-grid-accreditations">
                                <span>{t.ngoReg}: U88900RJ2025NPL109195</span>
                                <span>{t.ngoPan}: AAMCT5135C</span>
                                <span>✔ {t.ngo80g}</span>
                            </div>
                        </div>

                        <hr className="divider-line" />

                        {/* Record Details Grid */}
                        <div className="records-section">
                            <h4 className="section-title">
                                <FileText size={16} style={{ marginRight: '8px' }} />
                                {t.detailsHeader}
                            </h4>

                            <div className="records-grid">
                                <div className="record-item">
                                    <span className="record-label">{t.donorName}</span>
                                    <span className="record-value capitalize">{donation.donorName}</span>
                                </div>
                                <div className="record-item">
                                    <span className="record-label">{t.receiptNo}</span>
                                    <span className="record-value highlight-text">{donation.receiptNumber}</span>
                                </div>
                                <div className="record-item">
                                    <span className="record-label">{t.date}</span>
                                    <span className="record-value">{formattedDate}</span>
                                </div>
                                <div className="record-item">
                                    <span className="record-label">{t.amount}</span>
                                    <span className="record-value amount-text">₹{donation.amount}</span>
                                </div>
                                <div className="record-item">
                                    <span className="record-label">{t.paymentMethod}</span>
                                    <span className="record-value capitalize">{donation.paymentMethod === 'wallet' ? 'Wallet' : 'UPI / Online'}</span>
                                </div>
                                <div className="record-item">
                                    <span className="record-label">{t.status}</span>
                                    <span className="record-value status-success">
                                        <CheckCircle2 size={12} style={{ marginRight: '4px' }} />
                                        {t.successStatus}
                                    </span>
                                </div>
                            </div>
                        </div>

                        {/* 80G Stamp Badge if eligible */}
                        {donation.is80G && (
                            <div className="tax-benefit-banner">
                                <div className="stamp-80g">
                                    <span>80G</span>
                                    <span className="stamp-sub">BENEFIT</span>
                                </div>
                                <div className="tax-banner-text">
                                    <h5>{t.taxEligible}</h5>
                                    <p>{t.taxExemptSub}</p>
                                </div>
                            </div>
                        )}

                        {/* Actions */}
                        <div className="verify-actions">
                            {donation.receiptUrl && (
                                <a
                                    href={getPublicUrl(donation.receiptUrl)}
                                    target="_blank"
                                    rel="noreferrer"
                                    className="btn-download"
                                >
                                    <Download size={18} />
                                    {t.downloadBtn}
                                </a>
                            )}
                            <Link to="/" className="btn-home outline">
                                <Home size={18} />
                                {t.backHome}
                            </Link>
                        </div>
                    </motion.div>
                )}
            </div>
        </div>
    );
};

export default VerifyReceipt;
